/// Glyph index for a character (unknown characters become '?').
pub fn index(c: char) -> usize {
    let c = c.to_ascii_uppercase();
    let b = if c.is_ascii() { c as u8 } else { b'?' };
    if (FIRST..FIRST + COUNT as u8).contains(&b) { (b - FIRST) as usize } else { (b'?' - FIRST) as usize }
}

/// Atlas bitmap: COUNT cells of CELL_W x CELL_H pixels in one row, 255 = ink.
pub fn atlas() -> (Vec<u8>, usize, usize) {
    let (w, h) = (COUNT * CELL_W, CELL_H);
    let mut px = vec![0u8; w * h];
    for (g, cols) in GLYPHS.iter().enumerate() {
        for (cx, col) in cols.iter().enumerate() {
            for row in 0..7 {
                if col >> row & 1 == 1 {
                    px[(row + 1) * w + g * CELL_W + cx] = 255;
                }
            }
        }
    }
    (px, w, h)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_glyph_has_ink_except_space() {
        for (i, g) in GLYPHS.iter().enumerate() {
            let ink = g.iter().any(|&b| b != 0);
            assert_eq!(ink, i != 0, "glyph {i} ({})", (FIRST + i as u8) as char);
        }
    }

    #[test]
    fn indices_map_case_and_unknowns() {
        assert_eq!(index('a'), index('A'));
        assert_eq!(index('0'), 16);
        assert_eq!(index('я'), index('?'));
        assert_eq!(index('~'), index('?'));
    }

    #[test]
    fn atlas_has_the_expected_size_and_no_ink_in_spacing_column() {
        let (px, w, h) = atlas();
        assert_eq!((w, h), (384, 8));
        for g in 0..COUNT {
            for y in 0..h {
                assert_eq!(px[y * w + g * CELL_W + 5], 0);
            }
        }
        assert!(px.iter().any(|&p| p == 255));
    }
}
